import os
import re
import httpx
from fastapi import HTTPException
from app.ai.prompts import STUDY_NOTES_PROMPT

OLLAMA_BASE_URL = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434").rstrip("/")
OLLAMA_MODEL = os.getenv("OLLAMA_MODEL", "gemma4:e4b")


async def check_ollama_status() -> dict:
    """
    Checks if Ollama daemon is running and verifies if the required model is installed.
    """
    try:
        async with httpx.AsyncClient(timeout=5.0) as client:
            response = await client.get(f"{OLLAMA_BASE_URL}/api/tags")
            if response.status_code != 200:
                return {
                    "running": True,
                    "model_available": False,
                    "error": f"Ollama returned HTTP status {response.status_code}"
                }

            data = response.json()
            models = [m.get("name", "") for m in data.get("models", [])]
            # Match model name either exact or base tag (e.g., 'gemma4:e4b' or 'gemma4:e4b' in tag)
            model_found = any(OLLAMA_MODEL in m for m in models)

            return {
                "running": True,
                "model_available": model_found,
                "installed_models": models,
                "target_model": OLLAMA_MODEL
            }
    except httpx.ConnectError:
        return {
            "running": False,
            "model_available": False,
            "error": "Cannot connect to local Ollama. Please ensure Ollama is running on your machine."
        }
    except Exception as e:
        return {
            "running": False,
            "model_available": False,
            "error": str(e)
        }


def parse_model_response(raw_text: str) -> dict:
    """
    Parses the raw text generated by gemma4:e4b into four structured sections:
    explanation, summary, important_points, questions.
    """
    explanation = ""
    summary = ""
    important_points = []
    questions = []

    # Clean potential model thinking blocks or artifacts if present
    cleaned_text = re.sub(r"<thought>.*?</thought>", "", raw_text, flags=re.DOTALL).strip()

    # Split sections using headers: Explanation, Summary, Important Points, Practice Questions
    # Match patterns like '## 1. Explanation', '1. Explanation', '### Explanation', etc.
    section_pattern = re.compile(
        r"(?:^|\n)(?:#{1,4}\s*)?(?:[1-4]\.\s*)?(Explanation|Summary|Important Points|Key Points|Practice Questions|Questions)(?::|\n)",
        re.IGNORECASE
    )

    matches = list(section_pattern.finditer(cleaned_text))

    if matches:
        sections = {}
        for i, match in enumerate(matches):
            header = match.group(1).lower()
            start = match.end()
            end = matches[i + 1].start() if i + 1 < len(matches) else len(cleaned_text)
            content = cleaned_text[start:end].strip()

            if "explanation" in header:
                sections["explanation"] = content
            elif "summary" in header:
                sections["summary"] = content
            elif "point" in header:
                sections["important_points"] = content
            elif "question" in header:
                sections["questions"] = content

        explanation = sections.get("explanation", "")
        summary = sections.get("summary", "")

        # Parse important points
        raw_points = sections.get("important_points", "")
        for line in raw_points.split("\n"):
            line = line.strip()
            if line:
                cleaned_point = re.sub(r"^[-*•\d+.)\]]+\s*", "", line)
                if cleaned_point and len(cleaned_point) > 3:
                    important_points.append(cleaned_point)

        # Parse practice questions
        raw_q_text = sections.get("questions", "")
        # Parse Q&A pairs
        # Pattern handles 'Q1: ... Answer: ...', '1. ... Answer: ...', or 'Question: ... \n Answer: ...'
        qa_blocks = re.split(r"(?:^|\n)(?:Q\d*[:.]|\d+[\.\)]|Question\s*\d*[:.])\s*", raw_q_text, flags=re.IGNORECASE)
        for block in qa_blocks:
            block = block.strip()
            if not block:
                continue

            # Look for Answer separator
            ans_match = re.search(r"(?:^|\n)(?:Answer|Ans|A)[:.]\s*", block, re.IGNORECASE)
            if ans_match:
                q_part = block[:ans_match.start()].strip()
                a_part = block[ans_match.end():].strip()
                if q_part and a_part:
                    questions.append({"question": q_part, "answer": a_part})
            else:
                # If no explicit answer label found, store question if substantial
                if len(block) > 10:
                    questions.append({"question": block, "answer": "Refer to the notes explanation above."})

    # Fallback if structure was slightly unaligned in raw output
    if not explanation and cleaned_text:
        explanation = cleaned_text[:600]
    if not summary and cleaned_text:
        summary = cleaned_text[:250]
    if not important_points:
        important_points = [
            "Review key concepts highlighted in the uploaded notes.",
            "Verify relevant definitions and formulas.",
            "Test yourself using the practice questions."
        ]
    if not questions:
        questions = [
            {"question": "What is the primary topic covered in these notes?", "answer": "The main subject illustrated in the uploaded study notes."},
            {"question": "What is a key definition discussed in the material?", "answer": "Refer to the concept explanation section above."},
            {"question": "What formula or theorem is central to this topic?", "answer": "The governing equation stated in your notes."},
            {"question": "Why is this concept important for exam revision?", "answer": "It serves as a foundational building block for problem solving."},
            {"question": "How do you apply these notes in practice?", "answer": "By solving related exercises and checking your derivations."}
        ]

    # Ensure questions list has up to 5 questions
    if len(questions) > 5:
        questions = questions[:5]

    return {
        "explanation": explanation,
        "summary": summary,
        "important_points": important_points,
        "questions": questions
    }


async def generate_study_material(base64_image: str) -> dict:
    """
    Calls local Ollama gemma4:e4b model with the base64 image and returns structured study material.
    """
    # 1. First check if Ollama is running and has the model
    status = await check_ollama_status()
    if not status.get("running"):
        raise HTTPException(
            status_code=503,
            detail=(
                "Local Ollama service is not running. Please start Ollama on your Windows machine "
                "or run 'ollama serve' in PowerShell."
            )
        )

    if not status.get("model_available"):
        raise HTTPException(
            status_code=503,
            detail=(
                f"Required model '{OLLAMA_MODEL}' was not found in Ollama. "
                f"Please download it by running 'ollama pull {OLLAMA_MODEL}' in PowerShell."
            )
        )

    # 2. Execute inference request to Ollama
    payload = {
        "model": OLLAMA_MODEL,
        "prompt": STUDY_NOTES_PROMPT,
        "images": [base64_image],
        "stream": False,
        "options": {
            "temperature": 0.2,
            "top_p": 0.9
        }
    }

    try:
        # Local vision models may take 30-90s on GPU/CPU for high-resolution images
        async with httpx.AsyncClient(timeout=180.0) as client:
            response = await client.post(f"{OLLAMA_BASE_URL}/api/generate", json=payload)

            if response.status_code != 200:
                raise HTTPException(
                    status_code=502,
                    detail=f"Ollama returned an error during analysis (HTTP {response.status_code})."
                )

            data = response.json()
            raw_response = data.get("response", "").strip()

            if not raw_response:
                raise HTTPException(
                    status_code=500,
                    detail="The AI model generated an empty response. Please try with a clearer photo of your notes."
                )

            # 3. Parse and structure the response
            structured_data = parse_model_response(raw_response)
            return structured_data

    except httpx.ReadTimeout:
        raise HTTPException(
            status_code=504,
            detail="The analysis timed out. The local model took too long to process. Try uploading a smaller or cropped image."
        )
    except httpx.RequestError as e:
        raise HTTPException(
            status_code=502,
            detail="Communication error with local Ollama service. Please verify Ollama is still active."
        )
